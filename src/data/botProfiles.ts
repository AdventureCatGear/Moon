/** Aggregate stats derived from bot profiles */
export function getBotAggregateStats() {
  const total = botProfiles.length;
  const totalPlots = botProfiles.reduce((s, b) => s + b.plotsOwned, 0);
  const totalVotes = botProfiles.reduce((s, b) => s + b.votesParticipated, 0);
  const totalProposals = botProfiles.reduce((s, b) => s + b.proposalsSubmitted, 0);
  const byRisk = {
    conservative: botProfiles.filter((b) => b.riskProfile === "conservative").length,
    moderate: botProfiles.filter((b) => b.riskProfile === "moderate").length,
    aggressive: botProfiles.filter((b) => b.riskProfile === "aggressive").length,
  };
  const byZone = {
    MF: botProfiles.filter((b) => b.preferredZone === "MF").length,
    CP: botProfiles.filter((b) => b.preferredZone === "CP").length,
    CR: botProfiles.filter((b) => b.preferredZone === "CR").length,
  };
  const frameworks = [...new Set(botProfiles.map((b) => b.frameworkVendor))];
  return { total, totalPlots, totalVotes, totalProposals, byRisk, byZone, frameworks };
}
